export function colunasCsv(colecao: DefinicaoColecao): readonly ColunaCsv[] {
  const configuracao = colecao.exportacao;
  if (typeof configuracao === 'object' && configuracao.colunas)
    return configuracao.colunas;
  return colecao.esquema.campos
    .filter((c) => !c.virtual)
    .map((c) => ({ campo: c.nome, rotulo: rotulos[c.nome] ?? c.nome }));
}
